// Generates docs/RIG.md and the clip table inside docs/ANIMATION.md from the real code + model metadata.
import fs from "node:fs";
import { JOINT_DEFS, REQUIRED_MORPHS, EYE_TRAVEL, FINGERS } from "../src/engine/rig";
import { BUILTIN_CLIPS } from "../src/engine/library";
import { bakeClip, channelBones } from "../src/engine/clips";
import { JointSpace } from "../src/engine/rig";
import { loadModelNode } from "../tests/helpers/loadRobot";
import * as THREE from "three";

const meta = JSON.parse(fs.readFileSync("assets/models/robot_premium.rig.json", "utf8"));
type B = { name: string; parent: string | null; head: number[]; tail: number[] };
const bones: B[] = meta.bones;

const tree = (parent: string | null, depth = 0): string[] =>
  bones.filter((b) => b.parent === parent).flatMap((b) => [`${"  ".repeat(depth)}- \`${b.name}\``, ...tree(b.name, depth + 1)]);

const limitsRows = JOINT_DEFS.map((d) => {
  const f = (r: [number, number]) => (r[0] === r[1] ? "—" : `${r[0]} … ${r[1]}`);
  return `| \`${d.id}\`${d.mirror ? " (_L/_R)" : ""} | ${d.label} | ${d.order} | ${f(d.limits.x)} | ${f(d.limits.y)} | ${f(d.limits.z)} |`;
});
const morphRows = Object.entries(REQUIRED_MORPHS).map(([mesh, names]) => `| \`${mesh}\` | ${names.map((n) => `\`${n}\``).join(", ")} |`);

const md = `# Rig reference: bones, morph targets, joint space

> Generated by \`tools/gen_docs.ts\` from the code and \`assets/models/robot_premium.rig.json\`. Do not edit by hand.

All three styles (\`friendly\`, \`futuristic\`, \`premium\`) share **the same ${bones.length} bones** and the **same morph-target names**; only proportions/materials differ.
The engine refuses to load a GLB that lacks any of them (\`inspectRobotModel\` lists what is missing).

## Conventions

- Model space (glTF, Y-up): the robot faces **+Z**, its **left side is +X**, up is +Y. Units: meters. Height ≈ ${meta.height_m} m (premium).
- Bone names ending in \`_L\` are on the robot's left (+X), \`_R\` on its right (−X).
- **Joint space** — Blender bones have arbitrary local axes (Y along the bone, roll...), so the engine never exposes them.
  Every joint angle is a rotation about *model axes*, relative to the rest pose, applied in the parent's rest-aligned frame
  (\`local = P⁻¹ · d · P · restLocal\`, see \`src/engine/rig.ts\`). Consequences: the same numbers mean the same thing on every style and on both sides.
  - **X** = pitch about the left axis: positive rotates the top toward +Z (nod down / lean forward; a hanging arm swings *backward*).
  - **Y** = yaw about the up axis: positive turns toward the robot's left (+X).
  - **Z** = roll about the forward axis: positive tilts the top toward the robot's right (−X); for a left limb it swings the hanging limb outward (+X).
  - For right-side limbs (\`mirror\`) Y and Z are negated so a pose authored for the left side mirrors correctly.
  - Euler order per joint is listed below (chosen so the large-range axis is never the middle one, avoiding ±90° ambiguity).
- The semantic API (\`moveHead\`, \`moveArm\`) hides these signs: yaw + = left, pitch + = up, roll + = tilt left; shoulder + = forward raise, abduction + = outward, elbow + = flexion.

## Skeleton (${bones.length} bones)

${tree(null).join("\n")}

Eyes translate inside the visor plane instead of rotating (no tilt of the flat eye): \`eye_L/_R\` travel ±${EYE_TRAVEL.x * 100} cm horizontally and ±${EYE_TRAVEL.y * 100} cm vertically at ±${EYE_TRAVEL.maxYaw}° / ±${EYE_TRAVEL.maxPitch}° of gaze. Use \`robot.setEyeDirection({yaw,pitch})\` or \`lookAt\`.
Fingers: ${FINGERS.join(", ")} — two phalanges each (\`finger_<name>_1_<side>\`, \`finger_<name>_2_<side>\`); curl is Z, spread is X.

## Joint limits (degrees, left-side axes; right side is mirrored automatically)

| Joint | Label | Euler order | X range | Y range | Z range |
|---|---|---|---|---|---|
${limitsRows.join("\n")}

Limits are enforced for manual control (\`moveJoint\`, \`moveArm\`, \`moveHead\`), IK output and the Studio sliders; the built-in clips are tested to stay inside them.

## Morph targets (shape keys)

| Mesh | Targets |
|---|---|
${morphRows.join("\n")}

- Visemes follow the 15-viseme Oculus/OVR set (\`viseme_sil\` is the rest shape), so TTS/lip-sync tools that emit those names map 1:1.
- Eyes and mouth are *shape-key meshes skinned to the head* (not textures), so they are real 3D geometry that can be lit, and mirror/scale with the head.
- Names reach the engine through glTF \`mesh.extras.targetNames\` (three.js builds \`morphTargetDictionary\`).

## Meshes & materials (draw calls)

Meshes (all skinned): ${Object.keys(meta.meshes).join(", ")} — ${Object.keys(meta.meshes).length} draw calls per pass.
Materials (PBR metal/rough, no textures): ${meta.materials.join(", ")}. \`Mat_Glow\` (chest/ears/antenna) and \`Mat_Face\` (eyes/mouth/brows) are emissive; \`robot.setGlow(color)\` and \`robot.setEyeColor(color)\` recolor them at runtime.
`;
fs.writeFileSync("docs/RIG.md", md);

// animation table
const { parts } = await loadModelNode("premium");
const c = new THREE.Group();
c.add(parts.scene);
const js = new JointSpace(c);
const channels = channelBones();
void channels;
const rows = BUILTIN_CLIPS.map((d) => {
  const ch = [...bakeClip(d, js).keys()].join(", ");
  return `| \`${d.name}\` | ${d.loop ? "loop" : "one-shot"} | ${d.duration}s | ${d.priority} | ${ch} | ${d.description ?? ""} |`;
});
const table = `<!-- clips:start -->\n| Clip | Type | Length | Priority | Channels | Description |\n|---|---|---|---|---|---|\n${rows.join("\n")}\n<!-- clips:end -->`;
if (fs.existsSync("docs/ANIMATION.md")) {
  const a = fs.readFileSync("docs/ANIMATION.md", "utf8");
  fs.writeFileSync("docs/ANIMATION.md", a.replace(/<!-- clips:start -->[\s\S]*<!-- clips:end -->/, table));
}
console.log("docs generated:", bones.length, "bones,", BUILTIN_CLIPS.length, "clips");
